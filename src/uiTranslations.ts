export function translateUI(text: string, lang: "zh" | "en") {
  if (lang === "zh") return text;
  if (Object.hasOwn(english,text.trim())) return english[text.trim()];
  const synced = text.match(/^多目标观测已接入单目标学习，共(\d+)条已观测记录。$/);
  if (synced) return `Shared multi-objective observations: ${synced[1]} records are now observed.`;
  const linked = text.match(/(\d+)份构型验证记录需重新关联本机运行历史/);
  if (linked) return `Research data loaded; ${linked[1]} configuration references need to be relinked to server run history.`;
  return text;
}
